    def test_hsm_initialization_uses_tpm_enablement_not_device_access(self):
        name = "himmelblau-hsm-pin-init.service"
        for args in [
            {"tpmEnabled": False},
            {"tpmEnabled": True},
            {"tpmEnabled": True, "tcti": "swtpm:host=127.0.0.1,port=2321"},
        ]:
            with self.subTest(args=args):
                enabled = args["tpmEnabled"]
                evaluated = evaluate(**args)
                daemon = parse_unit(evaluated["units"]["himmelblaud.service"])
                self.assertEqual(
                    "LoadCredentialEncrypted" in daemon["Service"], enabled
                )
                self.assertEqual(
                    self.generated["himmelblaud.service"]["Service"]["Environment"]
                    in evaluated["units"]["himmelblaud.service"],
                    enabled,
                )
                self.assertEqual(name in evaluated["units"], enabled)
                for key in ["After", "Wants"]:
                    self.assertEqual(name in daemon["Unit"][key].split(), enabled)
                if enabled:
                    initializer = parse_unit(evaluated["units"][name])
                    for key in ["StateDirectory", "StateDirectoryMode", "BindPaths"]:
                        self.assertEqual(
                            initializer["Service"][key],
                            self.generated[name]["Service"][key],
                        )
                    for key in ["After", "Wants"]:
                        self.assertIn(
                            "tpm2-udev-trigger.service", initializer["Unit"][key].split()
                        )
                    self.assertEqual(
                        daemon["Service"]["LoadCredentialEncrypted"],
                        self.generated["himmelblaud.service"]["Service"][
                            "LoadCredentialEncrypted"
                        ],
                    )
                    self.assertEqual(
                        initializer["Install"]["WantedBy"],
                        self.generated[name]["Install"]["WantedBy"],
                    )
                for socket_name, text in evaluated["units"].items():
                    if socket_name.endswith(".socket"):
                        self.assertEqual(
                            name in parse_unit(text)["Unit"]["After"].split(), enabled
                        )


const MAX_LOG_SIZE: u64 = 5 * 1024 * 1024;

struct LogSink {
    file: File,
    path: PathBuf,
    size: u64,
}

impl LogSink {
    fn open(path: PathBuf) -> io::Result<Self> {
        let file = OpenOptions::new()
            .create(true)
            .append(true)
            .mode(0o600)
            .open(&path)?;
        file.set_permissions(std::fs::Permissions::from_mode(0o600))?;
        let size = file.metadata()?.len();
        let mut sink = Self { file, path, size };
        if size >= MAX_LOG_SIZE {
            sink.rotate()?;
        }
        Ok(sink)
    }

    fn rotate(&mut self) -> io::Result<()> {
        let old = self.path.with_extension("log.old");
        match std::fs::remove_file(&old) {
            Ok(()) => {}
            Err(err) if err.kind() == io::ErrorKind::NotFound => {}
            Err(err) => return Err(err),
        }
        std::fs::rename(&self.path, old)?;
        self.file = OpenOptions::new()
            .create_new(true)
            .append(true)
            .mode(0o600)
            .open(&self.path)?;
        self.size = 0;
        Ok(())
    }

    fn write(&mut self, bytes: &[u8]) -> io::Result<()> {
        if self.size > 0 && self.size.saturating_add(bytes.len() as u64) > MAX_LOG_SIZE {
            self.rotate()?;
        }
        self.file.write_all(bytes)?;
        self.size += bytes.len() as u64;
        Ok(())
    }
}

struct DiagnosticWriter(Arc<Mutex<LogSink>>);

impl Write for DiagnosticWriter {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        let stderr_result = io::stderr().write_all(bytes);
        let file_result = self
            .0
            .lock()
            .map_err(|_| io::Error::other("diagnostic log lock poisoned"))?
            .write(bytes);
        stderr_result?;
        file_result?;
        Ok(bytes.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        io::stderr().flush()?;
        self.0
            .lock()
            .map_err(|_| io::Error::other("diagnostic log lock poisoned"))?
            .file
            .flush()
    }
}

fn init_logging(state: &Path) {
    match LogSink::open(state.join("bridge.log")) {
        Ok(sink) => {
            let sink = Arc::new(Mutex::new(sink));
            tracing_subscriber::fmt()
                .with_writer(move || DiagnosticWriter(Arc::clone(&sink)))
                .init();
        }
        Err(err) => {
            eprintln!("Unable to open Collabora diagnostic log: {err}");
            tracing_subscriber::fmt::init();
        }
    }
}

#[derive(Parser)]
#[command(about = "Microsoft 365 file bridge for Collabora Office")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    Serve,
    /// Remove this user's provider registration and private bridge state.
    Cleanup,
}

#[derive(Serialize, Deserialize)]
struct Endpoint {
    port: u16,
    key: String,
}

impl Endpoint {
    fn is_valid(&self) -> bool {
        // Persist only an unprivileged listener and the two compact, lowercase
        // UUIDv4 values generated by serve. JSON validity alone is insufficient.
        if self.port < 1024
            || self.key.len() != 64
            || !self
                .key
                .bytes()
                .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
        {
            return false;
        }
        let (first, second) = self.key.split_at(32);
        [first, second].into_iter().all(|part| {
            uuid::Uuid::parse_str(part).is_ok_and(|id| {
                id.get_version() == Some(uuid::Version::Random)
                    && id.get_variant() == uuid::Variant::RFC4122
            })
        })
    }
}

fn endpoint_key() -> String {
    format!(
        "{}{}",
        uuid::Uuid::new_v4().simple(),
        uuid::Uuid::new_v4().simple()
    )
}

fn key_for_bound_port(previous: Option<Endpoint>, port: u16) -> String {
    // A stale profile can disclose its key to the process occupying the old
    // port. Reuse that key only when we actually bind the saved port again.
    previous
        .filter(|endpoint| endpoint.port == port)
        .map(|endpoint| endpoint.key)
        .unwrap_or_else(endpoint_key)
}

fn state_dir() -> Result<PathBuf> {
    if let Ok(path) = env::var("XDG_STATE_HOME") {
        return Ok(PathBuf::from(path).join("himmelblau-collabora"));
    }
    Ok(PathBuf::from(env::var("HOME").context("HOME is unset")?)
        .join(".local/state/himmelblau-collabora"))
}

fn lock_state(state: &Path) -> Result<File> {
    let parent = state.parent().context("Collabora state has no parent")?;
    std::fs::create_dir_all(parent)?;
    // Keep the lock outside the removable state directory. Never unlink it:
    // every bridge and cleanup process must contend on the same inode.
    let file = OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .mode(0o600)
        .open(state.with_extension("lock"))?;
    match fs2::FileExt::try_lock_exclusive(&file) {
        Ok(()) => {}
        Err(err) if err.kind() == io::ErrorKind::WouldBlock => {
            anyhow::bail!(
                "Another Collabora bridge or cleanup owns this state directory. Stop it and retry."
            );
        }
        Err(err) => return Err(err).context("Unable to lock Collabora state"),
    }
    file.set_permissions(std::fs::Permissions::from_mode(0o600))?;
    Ok(file)
}

fn cleanup_state(state: &Path, unregister: impl FnOnce() -> Result<()>) -> Result<()> {
    let _state_owner = lock_state(state)?;
    unregister()?;
    match std::fs::remove_dir_all(state) {
        Ok(()) => Ok(()),
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(err) => Err(err.into()),
    }
}

#[tokio::main]
async fn main() -> Result<()> {
    match Cli::parse().command {
        Command::Serve => serve().await,
        Command::Cleanup => cleanup_state(&state_dir()?, profile::remove),
    }
}

async fn serve() -> Result<()> {
    let state = state_dir()?;
    let _state_owner = lock_state(&state)?;
    std::fs::create_dir_all(&state)?;
    std::fs::set_permissions(&state, std::fs::Permissions::from_mode(0o700))?;
    init_logging(&state);
    let endpoint_path = state.join("endpoint.json");
    let previous = read_endpoint(&endpoint_path)?;
    let requested = previous.as_ref().map(|e| e.port).unwrap_or(0);
    let listener = bind_listener(requested).await?;
    let address: SocketAddr = listener.local_addr()?;
    let graph = graph::Graph::new()?;
    let key = key_for_bound_port(previous, address.port());
    write_endpoint(
        &endpoint_path,
        &Endpoint {
            port: address.port(),
            key: key.clone(),
        },
    )?;
    let app = server::App::new(graph, key.clone(), address, state);
    let provider_url = format!("http://{address}/?k={key}");
    let url = provider_url.clone();
    tokio::task::spawn_blocking(move || {
        if let Err(err) = profile::provision(&url) {
            tracing::warn!("Collabora registration pending: {err}");
        }
    })
    .await?;
    tokio::spawn(async move {
        let mut retry = tokio::time::interval(std::time::Duration::from_secs(30));
        loop {
            retry.tick().await;
            let url = provider_url.clone();
            let _ = tokio::task::spawn_blocking(move || profile::provision(&url)).await;
        }
    });
    tracing::info!(%address, "Collabora bridge listening");
    axum::serve(listener, app.router()).await?;
    Ok(())
}

fn read_endpoint(path: &Path) -> Result<Option<Endpoint>> {
    let bytes = match std::fs::read(path) {
        Ok(bytes) => bytes,
        Err(err) if err.kind() == io::ErrorKind::NotFound => return Ok(None),
        Err(err) => return Err(err.into()),
    };
    match serde_json::from_slice::<Endpoint>(&bytes) {
        Ok(endpoint) if endpoint.is_valid() => Ok(Some(endpoint)),
        _ => {
            tracing::warn!("Invalid saved Collabora endpoint; generating a new endpoint");
            Ok(None)
        }
    }
}

async fn bind_listener(requested: u16) -> io::Result<TcpListener> {
    match TcpListener::bind(("127.0.0.1", requested)).await {
        Ok(listener) => Ok(listener),
        Err(err) if requested != 0 && err.kind() == io::ErrorKind::AddrInUse => {
            tracing::warn!("Saved Collabora port is occupied; selecting a new port");
            TcpListener::bind(("127.0.0.1", 0)).await
        }
        Err(err) => Err(err),
    }
}

fn write_endpoint(path: &Path, endpoint: &Endpoint) -> Result<()> {
    let temporary = path.with_file_name(format!(".endpoint-{}.tmp", uuid::Uuid::new_v4()));
    let result = (|| -> Result<()> {
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o600)
            .open(&temporary)?;
        serde_json::to_writer(&mut file, endpoint)?;
        file.sync_all()?;
        std::fs::rename(&temporary, path)?;
        File::open(path.parent().context("Endpoint has no parent")?)?.sync_all()?;
        Ok(())
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(&temporary);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_owner_lock_is_exclusive_and_reusable() {
        let root = env::temp_dir().join(format!("collabora-lock-{}", uuid::Uuid::new_v4()));
        let state = root.join("first");
        let first = lock_state(&state).unwrap();
        assert!(lock_state(&state).is_err());
        let independent = lock_state(&root.join("second")).unwrap();
        assert_eq!(
            std::fs::metadata(state.with_extension("lock"))
                .unwrap()
                .permissions()
                .mode()
                & 0o777,
            0o600
        );
        drop(first);
        let replacement = lock_state(&state).unwrap();
        assert!(lock_state(&state).is_err());
        drop(replacement);
        drop(independent);
        std::fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn cleanup_requires_state_ownership_and_preserves_lock_inode() {
        use std::cell::Cell;
        use std::os::unix::fs::MetadataExt;

        let root = env::temp_dir().join(format!("collabora-lock-{}", uuid::Uuid::new_v4()));
        let state = root.join("himmelblau-collabora");
        let owner = lock_state(&state).unwrap();
        std::fs::create_dir(&state).unwrap();
        let recovery = state.join("recovery.bin");
        std::fs::write(&recovery, b"edits").unwrap();
        let lock_path = state.with_extension("lock");
        let inode = std::fs::metadata(&lock_path).unwrap().ino();
        let unregistered = Cell::new(false);
        assert!(cleanup_state(&state, || {
            unregistered.set(true);
            Ok(())
        })
        .is_err());
        assert!(!unregistered.get());
        assert_eq!(std::fs::read(&recovery).unwrap(), b"edits");
        drop(owner);
        cleanup_state(&state, || {
            unregistered.set(true);
            Ok(())
        })
        .unwrap();
        assert!(unregistered.get());
        assert!(!state.exists());
        assert_eq!(std::fs::metadata(&lock_path).unwrap().ino(), inode);
        let replacement = lock_state(&state).unwrap();
        assert!(cleanup_state(&state, || Ok(())).is_err());
        drop(replacement);
        // Cleanup remains idempotent when only the stable lockfile remains.
        cleanup_state(&state, || Ok(())).unwrap();
        assert_eq!(std::fs::metadata(&lock_path).unwrap().ino(), inode);
        std::fs::remove_dir_all(root).unwrap();
    }

    #[tokio::test]
    async fn occupied_saved_port_rotates_bootstrap_key() {
        let occupied = bind_listener(0).await.unwrap();
        let port = occupied.local_addr().unwrap().port();
        let old_key = endpoint_key();
        let replacement = bind_listener(port).await.unwrap();
        let bound_port = replacement.local_addr().unwrap().port();
        assert_ne!(port, bound_port);
        let key = key_for_bound_port(
            Some(Endpoint {
                port,
                key: old_key.clone(),
            }),
            bound_port,
        );
        assert_ne!(old_key, key);
        assert!(Endpoint {
            port: bound_port,
            key,
        }
        .is_valid());
    }

    #[test]
    fn unchanged_saved_port_retains_bootstrap_key() {
        let port = 12345;
        let old_key = endpoint_key();
        let key = key_for_bound_port(
            Some(Endpoint {
                port,
                key: old_key.clone(),
            }),
            port,
        );
        assert_eq!(old_key, key);
    }

    #[test]
    fn endpoint_repair_and_atomic_replacement() {
        let root = env::temp_dir().join(format!("collabora-endpoint-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir(&root).unwrap();
        let path = root.join("endpoint.json");
        assert!(read_endpoint(&path).unwrap().is_none());
        std::fs::write(&path, b"{broken").unwrap();
        assert!(read_endpoint(&path).unwrap().is_none());
        write_endpoint(
            &path,
            &Endpoint {
                port: 12345,
                key: endpoint_key(),
            },
        )
        .unwrap();
        assert_eq!(read_endpoint(&path).unwrap().unwrap().port, 12345);
        assert_eq!(
            std::fs::metadata(&path).unwrap().permissions().mode() & 0o777,
            0o600
        );
        assert_eq!(std::fs::read_dir(&root).unwrap().count(), 1);
        std::fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn malformed_saved_endpoint_values_are_not_reused() {
        let root = env::temp_dir().join(format!("collabora-endpoint-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir(&root).unwrap();
        let path = root.join("endpoint.json");
        let valid_key = "0123456789ab4def8123456789abcdef".repeat(2);
        let mut wrong_variant = valid_key.clone();
        wrong_variant.replace_range(16..17, "7");
        let mut wrong_version = valid_key.clone();
        wrong_version.replace_range(44..45, "1");
        for (port, key) in [
            (0, valid_key.clone()),
            (80, valid_key.clone()),
            (1023, valid_key.clone()),
            (12345, String::new()),
            (12345, "secret".into()),
            (12345, valid_key[..32].to_owned()),
            (12345, format!("{valid_key}0")),
            (12345, valid_key.to_uppercase()),
            (12345, "0".repeat(64)),
            (12345, "g".repeat(64)),
            (12345, "é".repeat(32)),
            (12345, wrong_variant),
            (12345, wrong_version),
        ] {
            write_endpoint(&path, &Endpoint { port, key }).unwrap();
            assert!(read_endpoint(&path).unwrap().is_none());
        }
        for port in [1024, 12345, u16::MAX] {
            let key = endpoint_key();
            write_endpoint(
                &path,
                &Endpoint {
                    port,
                    key: key.clone(),
                },
            )
            .unwrap();
            let endpoint = read_endpoint(&path).unwrap().unwrap();
            assert_eq!(endpoint.port, port);
            assert_eq!(endpoint.key, key);
        }
        std::fs::remove_dir_all(root).unwrap();
    }
}
